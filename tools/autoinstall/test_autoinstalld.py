class FileEventHandlerTests(unittest.TestCase):
    def setUp(self):
        autoinstalld.exit_event.clear()
        self._drain()
        self.handler = autoinstalld.FileEventHandler(
            patterns=["krohnkite*.kwinscript"], ignore_directories=True
        )

    def _drain(self) -> None:
        while not autoinstalld.install_queue.empty():
            autoinstalld.install_queue.get_nowait()

    def _queued(self) -> list[tuple[Path, bool]]:
        queued = []
        while not autoinstalld.install_queue.empty():
            path, is_final, _ = autoinstalld.install_queue.get_nowait()
            queued.append((path, is_final))
        return queued

    def test_created_event_is_not_final(self):
        self.handler.on_any_event(FileCreatedEvent("/tmp/builds/a.kwinscript"))
        self.assertEqual(self._queued(), [(Path("/tmp/builds/a.kwinscript"), False)])

    def test_closed_event_is_final(self):
        self.handler.on_any_event(FileClosedEvent("/tmp/builds/a.kwinscript"))
        self.assertEqual(self._queued(), [(Path("/tmp/builds/a.kwinscript"), True)])

    def test_closed_no_write_event_is_ignored(self):
        # Readers (the file manager, the indexer, kpackagetool6 itself) close
        # the archive without writing it. Installing on that close made every
        # installation trigger the next one.
        self.handler.on_any_event(FileClosedNoWriteEvent("/tmp/builds/a.kwinscript"))
        self.assertEqual(self._queued(), [])

    def test_opened_event_is_ignored(self):
        self.handler.on_any_event(FileOpenedEvent("/tmp/builds/a.kwinscript"))
        self.assertEqual(self._queued(), [])

    def test_moved_event_uses_the_destination(self):
        self.handler.on_any_event(
            FileMovedEvent("/tmp/incoming/a.kwinscript", "/tmp/builds/a.kwinscript")
        )
        self.assertEqual(self._queued(), [(Path("/tmp/builds/a.kwinscript"), False)])

    def test_move_out_of_the_folder_is_ignored(self):
        self.handler.on_any_event(FileMovedEvent("/tmp/builds/a.kwinscript", ""))
        self.assertEqual(self._queued(), [])


class InstallWorkerTests(unittest.TestCase):
    def setUp(self):
        autoinstalld.exit_event.clear()
        while not autoinstalld.install_queue.empty():
            autoinstalld.install_queue.get_nowait()

        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.installed: list[Path] = []

        self._install = mock.patch.object(
            autoinstalld,
            "kwin_script_install",
            side_effect=lambda package: (self.installed.append(package), True)[1],
        )
        self._interval = mock.patch.object(
            autoinstalld, "INSTALL_INTERVAL_SECONDS", 0.2
        )
        self._grace = mock.patch.object(autoinstalld, "CLOSE_GRACE_SECONDS", 0.4)
        self._duplicate = mock.patch.object(
            autoinstalld, "DUPLICATE_EVENT_SECONDS", 0.4
        )
        self._install.start()
        self._interval.start()
        self._grace.start()
        self._duplicate.start()

        self.worker = threading.Thread(target=autoinstalld.install_worker, daemon=True)
        self.worker.start()
        self.addCleanup(self._stop_worker)

    def _stop_worker(self) -> None:
        autoinstalld.exit_event.set()
        self.worker.join(timeout=3)
        self._duplicate.stop()
        self._grace.stop()
        self._interval.stop()
        self._install.stop()

    def _build(self, name: str) -> Path:
        package = self.tmp / name
        package.write_bytes(b"build")
        return package

    def _drop(self, package: Path, is_final: bool = True) -> None:
        autoinstalld.install_queue.put((package, is_final, time.monotonic()))

    def _wait_for(self, predicate, timeout: float = 3.0) -> bool:
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if predicate():
                return True
            time.sleep(0.02)
        return predicate()

    def test_build_that_was_only_created_is_installed(self):
        # watchdog reports a file moved into the folder as a creation and never
        # sends a close event for it.
        package = self._build("krohnkite-moved.kwinscript")
        self._drop(package, False)

        self.assertTrue(self._wait_for(lambda: self.installed == [package]))

    def test_build_dropped_under_another_name_is_installed_again(self):
        # KDE renames a conflicting copy to "name (1).kwinscript". Both files
        # are builds the user dropped, so both must be installed.
        first = self._build("krohnkite-dropped.kwinscript")
        second = self._build("krohnkite-dropped (1).kwinscript")
        self._drop(first)
        self.assertTrue(self._wait_for(lambda: self.installed == [first]))

        self._drop(second)
        self.assertTrue(self._wait_for(lambda: self.installed == [first, second]))

    def test_repeated_event_for_the_same_path_installs_once(self):
        package = self._build("krohnkite-once.kwinscript")
        self._drop(package)
        self._drop(package)
        self.assertTrue(self._wait_for(lambda: self.installed == [package]))

        time.sleep(0.6)
        self.assertEqual(self.installed, [package])

    def test_burst_of_builds_is_not_dropped(self):
        first = self._build("krohnkite-first.kwinscript")
        second = self._build("krohnkite-second.kwinscript")
        self._drop(first)
        self._drop(second)

        self.assertTrue(
            self._wait_for(lambda: first in self.installed and second in self.installed)
        )


